CREATE TABLE usuarios (
                          id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          nome            VARCHAR(120) NOT NULL,
                          cpf             VARCHAR(11)  NOT NULL UNIQUE,
                          data_nascimento DATE         NOT NULL,
                          sexo            VARCHAR(10)  NOT NULL,
                          email           VARCHAR(160) NOT NULL UNIQUE,
                          senha           VARCHAR(255) NOT NULL,
                          telefone        VARCHAR(20)  NOT NULL,
                          cidade          VARCHAR(100) NOT NULL,
                          uf              VARCHAR(2)   NOT NULL,
                          foto_url        VARCHAR(500),
                          data_cadastro   TIMESTAMP    NOT NULL
);

CREATE TABLE alunos (
                        usuario_id           BIGINT PRIMARY KEY REFERENCES usuarios (id),
                        matricula            VARCHAR(30) NOT NULL UNIQUE,
                        categoria_pretendida VARCHAR(2)  NOT NULL
);

CREATE TABLE instrutores (
                             usuario_id         BIGINT PRIMARY KEY REFERENCES usuarios (id),
                             numero_cnh         VARCHAR(20)      NOT NULL UNIQUE,
                             categoria_cnh      VARCHAR(2)       NOT NULL,
                             carro              VARCHAR(100)     NOT NULL,
                             placa_carro        VARCHAR(10)      NOT NULL,
                             preco_hora         NUMERIC(10,2)    NOT NULL,
                             bio                VARCHAR(1000),
                             anos_experiencia   INTEGER          NOT NULL,
                             status_verificacao VARCHAR(15)      NOT NULL,
                             nota_media         DOUBLE PRECISION NOT NULL
);